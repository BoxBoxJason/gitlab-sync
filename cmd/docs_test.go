package cmd

import (
	"os"
	"path/filepath"
	"reflect"
	"regexp"
	"strings"
	"testing"

	"github.com/boxboxjason/gitlab-sync/internal/utils"

	"github.com/spf13/cobra"
	"github.com/spf13/pflag"
)

const (
	// updateDocsEnv, when set, makes TestCLIReference rewrite the generated page instead of comparing it.
	updateDocsEnv = "UPDATE_DOCS"

	docsContentDir   = "../docs/content/docs"
	cliReferenceFile = "cli-reference.md"
	usageFile        = "usage.md"
	mappingFile      = "mapping.md"

	docsFilePermission = 0o600
	docsDirPermission  = 0o750
)

// envVarPattern finds the environment variables read by the CLI definition.
var envVarPattern = regexp.MustCompile(`(?:os\.Getenv|envString|envDuration)\("([A-Z][A-Z0-9_]*)"`)

// cliEnvVars returns the environment variables main.go reads.
func cliEnvVars(t *testing.T) []string {
	t.Helper()

	source, err := os.ReadFile("main.go")
	if err != nil {
		t.Fatalf("reading main.go: %v", err)
	}

	var names []string

	for _, match := range envVarPattern.FindAllStringSubmatch(string(source), -1) {
		names = append(names, match[1])
	}

	if len(names) == 0 {
		t.Fatal("found no environment variable in main.go, the pattern is out of date")
	}

	return names
}

// newDocumentedRootCmd builds the root command the way the documentation describes it:
// without any inherited environment, and with a placeholder version.
func newDocumentedRootCmd(t *testing.T) *cobra.Command {
	t.Helper()

	// Flag defaults are read from the environment, and the default User-Agent embeds the build version.
	for _, name := range cliEnvVars(t) {
		t.Setenv(name, "")
	}

	previousVersion := version
	version = "<version>"

	t.Cleanup(func() { version = previousVersion })

	var (
		args              utils.ParserArgs
		mirrorMappingPath string
		logFile           string
	)

	rootCmd := buildRootCmd(&args, &mirrorMappingPath, &logFile)
	rootCmd.InitDefaultHelpFlag()
	rootCmd.InitDefaultVersionFlag()

	return rootCmd
}

// renderCLIReference renders the help of every command as a documentation page.
func renderCLIReference(rootCmd *cobra.Command) string {
	var page strings.Builder

	page.WriteString("---\ntitle: CLI reference\ndescription: \"Generated help of every gitlab-sync command and flag, with defaults, so the reference always matches the CLI.\"\nweight: 50\n---\n\n")
	page.WriteString("<!-- Code generated by TestCLIReference (run `make docs-generate`); DO NOT EDIT. -->\n\n")
	page.WriteString("{{< callout type=\"info\" >}}\nThis page is generated from the CLI definition, so it always matches the released flags.\n{{< /callout >}}\n")

	commands := append([]*cobra.Command{rootCmd}, rootCmd.Commands()...)
	for _, command := range commands {
		page.WriteString("\n## " + command.CommandPath() + "\n\n")

		if description := strings.TrimSpace(command.Long); description != "" {
			page.WriteString(description + "\n\n")
		}

		page.WriteString("```text\n" + strings.TrimSpace(command.UsageString()) + "\n```\n")
	}

	return page.String()
}

// TestCLIReference fails when the generated CLI reference no longer matches the CLI.
// Regenerate it with `make docs-generate`.
func TestCLIReference(t *testing.T) {
	want := renderCLIReference(newDocumentedRootCmd(t))
	path := filepath.Join(docsContentDir, cliReferenceFile)

	if os.Getenv(updateDocsEnv) != "" {
		t.Setenv(updateDocsEnv, "")

		if err := os.MkdirAll(filepath.Dir(path), docsDirPermission); err != nil {
			t.Fatalf("creating the docs directory: %v", err)
		}

		if err := os.WriteFile(path, []byte(want), docsFilePermission); err != nil {
			t.Fatalf("writing %s: %v", path, err)
		}

		return
	}

	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("reading %s: %v (run `make docs-generate`)", path, err)
	}

	if string(got) != want {
		t.Fatalf("%s is out of date, run `make docs-generate` and commit the result", path)
	}
}

func readDocsPage(t *testing.T, name string) string {
	t.Helper()

	content, err := os.ReadFile(filepath.Join(docsContentDir, name))
	if err != nil {
		t.Fatalf("reading the %s documentation page: %v", name, err)
	}

	return string(content)
}

// TestDocsCoverEveryFlag fails when a flag is added to the CLI without being documented in the usage page.
func TestDocsCoverEveryFlag(t *testing.T) {
	usage := readDocsPage(t, usageFile)

	newDocumentedRootCmd(t).Flags().VisitAll(func(flag *pflag.Flag) {
		if flag.Name == "help" || flag.Name == "version" {
			return
		}

		if !strings.Contains(usage, "`--"+flag.Name+"`") {
			t.Errorf("flag --%s is not documented in docs/content/docs/%s", flag.Name, usageFile)
		}
	})
}

// TestDocsCoverEveryEnvVar fails when an environment variable is read without being documented in the usage page.
func TestDocsCoverEveryEnvVar(t *testing.T) {
	usage := readDocsPage(t, usageFile)

	for _, name := range cliEnvVars(t) {
		if !strings.Contains(usage, "`"+name+"`") {
			t.Errorf("environment variable %s is not documented in docs/content/docs/%s", name, usageFile)
		}
	}
}

// TestDocsCoverEveryMappingOption fails when a mirror mapping option is added without being documented.
func TestDocsCoverEveryMappingOption(t *testing.T) {
	mapping := readDocsPage(t, mappingFile)
	options := reflect.TypeFor[utils.MirroringOptions]()

	for field := range options.Fields() {
		name, _, _ := strings.Cut(field.Tag.Get("json"), ",")
		if name == "" || name == "-" {
			continue
		}

		if !strings.Contains(mapping, "| `"+name+"` |") {
			t.Errorf("mapping option %s is not documented in docs/content/docs/%s", name, mappingFile)
		}
	}
}
